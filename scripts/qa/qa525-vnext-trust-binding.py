#!/usr/bin/env python3
"""QA525 admission-to-approval BYTE BINDING only. No signature verifier or APPLY.

Inputs are untrusted until a separately installed, authenticated bootstrap
verifies a signed, independent approval record and OPS/program provenance.
This pure helper must NEVER be used as evidence that the record is signed,
the Sponsor consented, G6 is real, the filesystem is trusted or QA was applied.
No filesystem, network, subprocess, Docker, host or cryptographic key access.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import hmac
import json
import re

MAX_RECEIPT_BYTES = 65536
SHA = re.compile(r"[0-9a-f]{40}\Z")
DIGEST = re.compile(r"sha256:[0-9a-f]{64}\Z")
NONCE = re.compile(r"[A-Za-z0-9_-]{24,96}\Z")
ISO_UTC = re.compile(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ\Z")
ADMISSION_FIELDS = frozenset({
    "schema", "status", "ops_source_sha", "app_source_sha", "artifact_id",
    "artifact_sha256", "silo_workflow_run", "signed_installable_sha256",
    "artifact_identity", "manifest_sha256", "attestation_bundle_sha256",
    "policy_hash", "nonce", "nonce_consumed", "nonce_consume_transition",
    "admitted_at", "valid_until", "g6_expires_at", "network_allowed",
})
ANCHOR_FIELDS = frozenset({
    "schema", "status", "scope", "host", "environment",
    "nonce", "admission_sha256", "ops_source_sha", "app_source_sha",
    "policy_hash", "artifact_id", "artifact_sha256",
    "signed_installable_sha256", "manifest_sha256",
    "attestation_bundle_sha256", "artifact_identity",
    "g6_review_sha256", "sponsor_approval_sha256",
    "silo_workflow_run", "g6_expires_at",
    "issued_at", "expires_at",
})
SAME_FIELDS = (
    "nonce", "ops_source_sha", "app_source_sha", "policy_hash",
    "artifact_id", "artifact_sha256", "signed_installable_sha256",
    "manifest_sha256", "attestation_bundle_sha256", "artifact_identity",
    "silo_workflow_run", "g6_expires_at",
)
IDENTITY_FIELDS = {"device", "inode", "size", "mtime_ns"}


class Stop(Exception):
    """Static fail-closed reason, free of confidential input."""


def _unique(pairs):
    result = {}
    for k, v in pairs:
        if k in result:
            raise Stop("BINDING_DUPLICATE_JSON_KEY")
        result[k] = v
    return result


def _parse(raw, label):
    if type(raw) is not bytes or not 0 < len(raw) <= MAX_RECEIPT_BYTES:
        raise Stop("BINDING_" + label + "_SIZE")
    try:
        doc = json.loads(raw.decode("utf-8"), object_pairs_hook=_unique,
                         parse_constant=lambda _: (_ for _ in ()).throw(
                             Stop("BINDING_NONFINITE_NUMBER")))
    except Stop:
        raise
    except (UnicodeDecodeError, ValueError, TypeError, RecursionError):
        raise Stop("BINDING_" + label + "_JSON_INVALID") from None
    if type(doc) is not dict:
        raise Stop("BINDING_" + label + "_NOT_OBJECT")
    # Admission v2 is generated by json.dumps(sort_keys=True)+"\n".
    if label == "ADMISSION":
        try:
            expected = (json.dumps(doc, sort_keys=True, ensure_ascii=True,
                                   allow_nan=False) + "\n").encode("utf-8")
        except (ValueError, TypeError, RecursionError):  # e.g. 1e999 parses to inf
            raise Stop("BINDING_ADMISSION_NONCANONICAL") from None
        if raw != expected:
            raise Stop("BINDING_ADMISSION_NONCANONICAL")
    return doc


def _utc(value, code):
    if type(value) is not str or ISO_UTC.fullmatch(value) is None:
        raise Stop(code)
    try:
        return dt.datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ").replace(
            tzinfo=dt.timezone.utc)
    except ValueError:
        raise Stop(code) from None


def _clock(now):
    if type(now) is not dt.datetime or now.tzinfo is None:
        raise Stop("BINDING_CLOCK_INVALID")
    value = now.astimezone(dt.timezone.utc)
    if value.utcoffset() != dt.timedelta(0):
        raise Stop("BINDING_CLOCK_INVALID")
    return value


def _digest(value):
    return type(value) is str and DIGEST.fullmatch(value) is not None


def _sha(value):
    return type(value) is str and SHA.fullmatch(value) is not None


def _identity(value):
    return (type(value) is dict and set(value) == IDENTITY_FIELDS
            and all(type(v) is int and v >= 0 for v in value.values())
            and value["size"] > 0)


def bind(admission_bytes: bytes, external_approval_bytes: bytes, *,
         trusted_policy_hash: str, now: dt.datetime) -> dict:
    """Compare admission BYTES to an externally authenticated approval claim.

    This function cannot establish the record's provenance. A signed, pinned
    OPS bootstrap must verify the independent approval's authenticity and
    retain both files on trusted descriptors before using the returned digest.
    Returns only a non-authorizing consistency result; no file is modified.
    """
    current = _clock(now)
    if not _digest(trusted_policy_hash):
        raise Stop("BINDING_TRUSTED_POLICY_INVALID")
    admission = _parse(admission_bytes, "ADMISSION")
    anchor = _parse(external_approval_bytes, "ANCHOR")
    if set(admission) != ADMISSION_FIELDS or set(anchor) != ANCHOR_FIELDS:
        raise Stop("BINDING_FIELDS_INVALID")
    for key, expected in {
        "schema": "qa525-admission-v2", "status": "ADMITTED",
        "nonce_consumed": False, "nonce_consume_transition": "APPLYING",
        "network_allowed": False,
    }.items():
        if type(admission[key]) is not type(expected) or admission[key] != expected:
            raise Stop("BINDING_ADMISSION_STATE_INVALID")
    for key, expected in {
        "schema": "qa525-approval-anchor-v1",
        "status": "BYTE_BINDING_INPUT_ONLY_NOT_VERIFIED_HERE",
        "scope": "API_WEB_QA_ONLY", "host": "glmdch",
        "environment": "QA_SYNTHETIC",
    }.items():
        if anchor[key] != expected:
            raise Stop("BINDING_ANCHOR_SCOPE_INVALID")
    if not (_sha(admission["app_source_sha"])
            and _sha(admission["ops_source_sha"])
            and type(admission["nonce"]) is str
            and NONCE.fullmatch(admission["nonce"])
            and type(admission["artifact_id"]) is int
            and admission["artifact_id"] > 0
            and type(admission["silo_workflow_run"]) is int
            and admission["silo_workflow_run"] > 0
            and _identity(admission["artifact_identity"])
            and all(_digest(admission[key]) for key in (
                "artifact_sha256", "signed_installable_sha256",
                "manifest_sha256", "attestation_bundle_sha256", "policy_hash"
            ))):
        raise Stop("BINDING_ADMISSION_VALUE_INVALID")
    if not all(_digest(anchor[key]) for key in (
        "admission_sha256", "g6_review_sha256", "sponsor_approval_sha256"
    )):
        raise Stop("BINDING_ANCHOR_DIGEST_INVALID")
    if not hmac.compare_digest(admission["policy_hash"], trusted_policy_hash):
        raise Stop("BINDING_POLICY_MISMATCH")
    if (not _identity(anchor["artifact_identity"])
            or type(anchor["silo_workflow_run"]) is not int
            or any(type(anchor[key]) is not type(admission[key])
                   or anchor[key] != admission[key] for key in SAME_FIELDS)):
        raise Stop("BINDING_CUT_MISMATCH")
    digest = "sha256:" + hashlib.sha256(admission_bytes).hexdigest()
    if not hmac.compare_digest(anchor["admission_sha256"], digest):
        raise Stop("BINDING_ADMISSION_DIGEST_MISMATCH")
    admitted = _utc(admission["admitted_at"], "BINDING_ADMITTED_TIME_INVALID")
    until = _utc(admission["valid_until"], "BINDING_ADMISSION_EXPIRY_INVALID")
    g6 = _utc(admission["g6_expires_at"], "BINDING_G6_EXPIRY_INVALID")
    issued = _utc(anchor["issued_at"], "BINDING_APPROVAL_TIME_INVALID")
    expiry = _utc(anchor["expires_at"], "BINDING_APPROVAL_TIME_INVALID")
    if (not admitted <= current < min(until, g6, expiry)
            or not admitted <= issued <= current
            or until - admitted > dt.timedelta(minutes=30)
            or expiry - issued > dt.timedelta(minutes=30)
            or expiry <= issued):
        raise Stop("BINDING_WINDOW_INVALID")
    return {
        "status": "BYTE_BINDING_MATCH_ONLY_EXTERNAL_AUTH_NOT_VERIFIED",
        "admission_sha256": digest,
        "external_anchor_sha256": "sha256:" + hashlib.sha256(external_approval_bytes).hexdigest(),
        "nonce": admission["nonce"],
        "app_source_sha": admission["app_source_sha"],
        "ops_source_sha": admission["ops_source_sha"],
        "valid_until": min(until, g6, expiry).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "signature_verified_here": False,
        "g6_verified_here": False,
        "sponsor_approved_here": False,
        "may_apply": False,
        "may_install": False,
    }


if __name__ == "__main__":
    raise SystemExit("QA525_TRUST_BINDING_LIBRARY_ONLY_NO_EXECUTION")
