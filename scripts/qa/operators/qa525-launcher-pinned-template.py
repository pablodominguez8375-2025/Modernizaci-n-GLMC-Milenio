#!/usr/bin/env python3
"""Pure QA525 SHA-pinned launcher template, NOT a signed installer.

This module only creates reproducible candidate *bytes* for the future
root-only transactional installer. The source SHA is NOT cryptographic proof:
the installer must independently verify GitHub exact-head, Sigstore, signed
manifest, root-owned immutable package, approval and five exclusive locks.
No filesystem access, network, root checks or installation occurs here.
"""
import ast
import hashlib
from pathlib import PurePosixPath
import re

SHA = re.compile(r"[0-9a-f]{40}")
RELEASE_ROOT = PurePosixPath("/opt/centenario/qa525-signed-stage")
ENTRY_REL = PurePosixPath("scripts/qa/operators/qa525-update.py")
STATUS = "SHA_PINNED_LAUNCHER_TEMPLATE_NO_INSTALL"


class Blocked(Exception):
    """Fixed, non-sensitive security reason."""


def pinned_source_path(source_sha):
    """Refuse mutable names, traversal, suffixes and caller-selected paths."""
    if type(source_sha) is not str or SHA.fullmatch(source_sha) is None:
        raise Blocked("LAUNCHER_SOURCE_SHA_NOT_EXACT")
    path = RELEASE_ROOT / source_sha / ENTRY_REL
    if (not path.is_absolute() or path.parts[:len(RELEASE_ROOT.parts)]
            != RELEASE_ROOT.parts or path.name != "qa525-update.py"):
        raise Blocked("LAUNCHER_PINNED_SOURCE_PATH_INVALID")
    return path


def render(source_sha):
    """Render the historically supported launcher with ONE immutable target.

    The only variable is an exact lower-case 40-hex source SHA. The template
    never loads the candidate or attempts to verify its signature itself.
    """
    source = str(pinned_source_path(source_sha))
    payload = (
        '#!/usr/bin/python3\nimport os,sys\n'
        'os.execv("/usr/bin/python3", ["/usr/bin/python3", "-B", '
        + repr(source) + ', *sys.argv[1:]])\n'
    )
    return payload.encode("utf-8")


def inspect_template(source_sha, candidate):
    """Validate generated bytes for an exact signed-release *identity* only.

    Equality with this template is not proof of the source's signature or
    availability on disk. This result has no installation/deploy authority.
    """
    expected = render(source_sha)
    if type(candidate) is not bytes or candidate != expected:
        raise Blocked("LAUNCHER_TEMPLATE_OR_SOURCE_MISMATCH")
    # Ensure the generated script is valid Python, without executing it.
    try:
        ast.parse(candidate.decode("utf-8"))
    except (UnicodeError, SyntaxError, ValueError):
        raise Blocked("LAUNCHER_TEMPLATE_SYNTAX_INVALID") from None
    return {
        "status": STATUS,
        "source_sha": source_sha,
        "pinned_operator_path": str(pinned_source_path(source_sha)),
        "launcher_sha256": hashlib.sha256(candidate).hexdigest(),
        "template_format": "EXACT_LEGACY_OS_EXECV_SHA_PINNED",
        "signature_verified_by_template": False,
        "package_installed_by_template": False,
        "may_install": False,
        "may_apply": False,
    }


if __name__ == "__main__":
    raise SystemExit("LAUNCHER_TEMPLATE_LIBRARY_ONLY_NO_INSTALL_ENTRYPOINT")
